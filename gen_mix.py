#!/usr/bin/env python3
"""Generate the mix benchmark in all seven languages from one round table,
so the 64-round kernel cannot diverge between implementations."""

ROUNDS = 64
SHIFTS = [13, 16, 7, 11, 29, 19, 23, 5]
CONSTS = [2654435761, 1274126177, 1013904223, 1664525, 2246822519, 3266489917,
          668265263, 374761393]
N = 16_000_000


def rounds():
    return [(CONSTS[r % len(CONSTS)], SHIFTS[r % len(SHIFTS)])
            for r in range(ROUNDS)]


def peregrine():
    body = ["        var h: u32 = a[i] + i;",
            "        h = h * 2654435761;"]
    for c, s in rounds():
        body.append(f"        h = h ^ (h >> {s});")
        body.append(f"        h = h * {c};")
    body.append("        a[i] = h;")
    return f"""// mix.peregrine -- {ROUNDS}-round u32 mix chain, in place over one stream.
// A dense integer-hashing workload (PRNG seeding / key-schedule shape).
// Wrapping is defined, the checksum is exact, and every implementation
// runs the identical round table generated by gen_mix.py.

const N: u32 = {N};

fn main() {{
    var a: buf<u32>(N);
    for i in 0..N {{
        a[i] = i;
    }}
    for i in 0..N {{
{chr(10).join(body)}
    }}
    var sum: u64 = 0;
    var xorc: u32 = 0;
    for i in 0..N {{
        sum += a[i];
        xorc = xorc ^ a[i];
    }}
    print(sum, " ", xorc, " ", N);
}}
"""


def csrc():
    body = ["        uint32_t h = a[i] + (uint32_t)i;",
            "        h *= 2654435761u;"]
    for c, s in rounds():
        body.append(f"        h ^= h >> {s};")
        body.append(f"        h *= {c}u;")
    body.append("        a[i] = h;")
    return f"""// Natural C: one malloc'd uint32_t array, plain loops, built with -O2.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

int main(void) {{
    size_t N = {N};
    uint32_t* a = malloc(N * sizeof(uint32_t));
    for (size_t i = 0; i < N; i++) {{
        a[i] = (uint32_t)i;
    }}
    for (size_t i = 0; i < N; i++) {{
{chr(10).join(body)}
    }}
    uint64_t sum = 0, x = 0;
    for (size_t i = 0; i < N; i++) {{
        sum += a[i];
        x ^= a[i];
    }}
    printf("%llu %llu %zu\\n", (unsigned long long)sum,
           (unsigned long long)x, N);
    return 0;
}}
"""


def cpp():
    body = ["        uint32_t h = a[i] + (uint32_t)i;",
            "        h *= 2654435761u;"]
    for c, s in rounds():
        body.append(f"        h ^= h >> {s};")
        body.append(f"        h *= {c}u;")
    body.append("        a[i] = h;")
    return f"""// Idiomatic C++: one std::vector<uint32_t>, plain loops, built with -O2.
#include <cstdint>
#include <cstdio>
#include <vector>

int main() {{
    const uint64_t N = {N};
    std::vector<uint32_t> a(N);
    for (uint64_t i = 0; i < N; i++) {{
        a[i] = (uint32_t)i;
    }}
    for (uint64_t i = 0; i < N; i++) {{
{chr(10).join(body)}
    }}
    uint64_t sum = 0, xorc = 0;
    for (uint64_t i = 0; i < N; i++) {{
        sum += a[i];
        xorc ^= a[i];
    }}
    printf("%llu %llu %llu\\n", (unsigned long long)sum,
           (unsigned long long)xorc, (unsigned long long)N);
    return 0;
}}
"""


def rust():
    body = ["            let mut h = a[i as usize].wrapping_add(i as u32);",
            "            h = h.wrapping_mul(2654435761);"]
    for c, s in rounds():
        body.append(f"            h ^= h >> {s};")
        body.append(f"            h = h.wrapping_mul({c});")
    body.append("            a[i as usize] = h;")
    return f"""// Safe idiomatic Rust: one Vec<u32>, wrapping ops, built with rustc -O.
fn main() {{
    let n: u64 = {N};
    let mut a = vec![0u32; n as usize];
    for i in 0..n {{
        a[i as usize] = i as u32;
    }}
    for i in 0..n {{
{chr(10).join(body)}
    }}
    let mut sum: u64 = 0;
    let mut xorc: u32 = 0;
    for i in 0..n {{
        sum = sum.wrapping_add(a[i as usize] as u64);
        xorc ^= a[i as usize];
    }}
    println!("{{}} {{}} {{}}", sum, xorc, n);
}}
"""


def goose():
    body = ["        var h: u32 = a[i] + (i as u32);",
            "        h = h * 2654435761;"]
    for c, s in rounds():
        body.append(f"        h = h ^ (h >> {s});")
        body.append(f"        h = h * {c};")
    body.append("        a[i] = h;")
    return f"""// Goose: one fixed u32 array, same round table, same checksum.
import std;

fn main() {{
    var a: u32[{N}] = [0; {N}];
    for i in {N} {{
        a[i] = (i as u32);
    }}
    for i in {N} {{
{chr(10).join(body)}
    }}
    var sum: u64 = 0;
    var xorc: u32 = 0;
    for i in {N} {{
        sum += a[i];
        xorc = xorc ^ a[i];
    }}
    print(sum, " ", xorc, " ", {N});
}}
"""


def go():
    body = ["        h := a[i] + uint32(i)",
            "        h *= 2654435761"]
    for c, s in rounds():
        body.append(f"        h ^= h >> {s}")
        body.append(f"        h *= {c}")
    body.append("        a[i] = h")
    return f"""// Go: one []uint32 slice, plain loops, built with go build.
package main

import "fmt"

func main() {{
	const n = {N}
	a := make([]uint32, n)
	for i := 0; i < n; i++ {{
		a[i] = uint32(i)
	}}
	for i := 0; i < n; i++ {{
{chr(10).join(body)}
	}}
	var sum uint64
	var xorc uint32
	for i := 0; i < n; i++ {{
		sum += uint64(a[i])
		xorc ^= a[i]
	}}
	fmt.Println(sum, xorc, n)
}}
"""


def py():
    pairs = ", ".join(f"({c}, {s})" for c, s in rounds())
    return f"""# Pure CPython: same round table, same wrapping arithmetic (masked),
# same checksum. Slow by three orders of magnitude -- that is the point
# of the row, not a strawman: this is what the language gives you.
import os

M32 = 0xFFFFFFFF
N = int(os.environ.get("BENCH_N", "{N}"))
ROUNDS = [{pairs}]

a = list(range(N))
for i in range(N):
    h = (a[i] + i) & M32
    h = (h * 2654435761) & M32
    for c, s in ROUNDS:
        h = (h ^ (h >> s)) & M32
        h = (h * c) & M32
    a[i] = h

total = 0
xorc = 0
for v in a:
    total += v
    xorc ^= v
print(total, xorc & M32, N)
"""


import os
HERE = "/home/z/my-project/scripts/verify"
for name, src in [("mix_prn.peregrine", peregrine()), ("mix_c.c", csrc()),
                  ("mix_idio.cpp", cpp()), ("mix_safe.rs", rust()),
                  ("mix_goose.goose", goose()), ("mix_go.go", go()),
                  ("mix_py.py", py())]:
    with open(os.path.join(HERE, name), "w") as f:
        f.write(src)
    print("wrote", name, len(src), "bytes")
